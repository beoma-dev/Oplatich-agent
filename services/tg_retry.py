"""Повтор исходящих вызовов Telegram на сетевых сбоях.

Канал до Telegram идёт через прокси и теряет часть вызовов: замеры отчёта
005 дали 10–17 % отказов на вызов, и все они приходились на сеть, а не на
отказ Telegram по смыслу. Один потерянный вызов — это не «моргнуло», а не
дошедшее до человека уведомление: карточка финансисту, ответ автору
о смене статуса, напоминание об оплате. Три попытки превращают 13 %
в доли процента, и это не зависит от того, какой прокси стоит снаружи.

Механизм не новый: он год работал внутри `notifier.py` для карточки
финансиста — единственного пути, который сочли достаточно важным. Отчёт
005 показал, что остальные пути ничем не менее важны, поэтому он вынесен
сюда целиком, без изменения поведения.

Повторяем ТОЛЬКО `NetworkError`. Отказы по смыслу — бот заблокирован, чат
не найден, «message is not modified» — повторять бессмысленно: они
прилетают другими исключениями и уходят наверх сразу.
"""
from __future__ import annotations

import asyncio
import logging
from collections.abc import Awaitable, Callable
from typing import TypeVar

from telegram.error import NetworkError

log = logging.getLogger(__name__)

# Паузы между попытками, в секундах. Бюджет короткий намеренно: подача
# заявки ждёт отправки карточки, и лучше отдать управление человеку, чем
# держать его в неведении минуту.
DEFAULT_PAUSES: tuple[float, ...] = (1.0, 3.0)

# Для отправок, которых никто не ждёт на экране: бэкап уходит раз в сутки,
# и там разумнее подождать подольше, чем потерять копию.
PATIENT_PAUSES: tuple[float, ...] = (5.0, 30.0, 120.0)

T = TypeVar("T")


async def send_with_retry(
    send: Callable[[], Awaitable[T]],
    *,
    what: str = "вызов Telegram",
    pauses: tuple[float, ...] = DEFAULT_PAUSES,
) -> T | None:
    """Выполняет `send()`, повторяя его на сетевых сбоях.

    Возвращает результат последней успешной попытки. Если сеть не поднялась
    за все попытки — пробрасывает исключение: решать, что делать с потерей,
    должен вызывающий, а не этот модуль.
    """
    for attempt, pause in enumerate((*pauses, None), start=1):
        try:
            return await send()
        except NetworkError as err:
            if pause is None:
                raise
            log.warning(
                "%s: сеть недоступна (%s), попытка %s из %s через %.0f с",
                what, err.__class__.__name__, attempt, len(pauses) + 1, pause,
            )
            await asyncio.sleep(pause)
    return None
